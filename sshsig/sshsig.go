// Package sshsig signs and verifies SSH signatures (SSHSIG), the format of
// "ssh-keygen -Y sign" and "ssh-keygen -Y verify", as specified in OpenSSH's
// PROTOCOL.sshsig.
//
// Its API is exactly the one accepted for golang.org/x/crypto/ssh in proposal
// golang/go#68197. When x/crypto ships it, callers switch the import and this
// package is deleted.
//
// Signatures are the raw SSHSIG blob. The armored form ssh-keygen writes is
// that blob PEM-encoded with type "SSH SIGNATURE".
package sshsig

import (
	"bytes"
	"crypto/sha256"
	"crypto/sha512"
	"encoding/binary"
	"errors"
	"fmt"
	"io"
	"math"

	"golang.org/x/crypto/ssh"
)

const (
	magicPreamble = "SSHSIG"
	sigVersion    = 1
)

// Sign returns a detached SSH Signature for the provided message.
//
// The namespace is a domain-specific identifier for the context in which the
// signature will be used. It must match between the Sign and [Verify] calls. A
// fully-qualified suffix is recommended, e.g. "receiptV2@example.com".
//
// These signatures are compatible with those generated by "ssh-keygen -Y sign",
// and can be verified with [Verify] or "ssh-keygen -Y verify". The returned
// bytes are usually PEM encoded with [encoding/pem] and type "SSH SIGNATURE".
//
// If the Signer has an RSA PublicKey, it must also implement
// [ssh.AlgorithmSigner]. If it also implements [ssh.MultiAlgorithmSigner], the
// first algorithm returned by Algorithms will be used, otherwise
// "rsa-sha2-512" is used.
func Sign(s ssh.Signer, rand io.Reader, message []byte, namespace string) ([]byte, error) {
	if namespace == "" {
		return nil, errors.New("sshsig: empty namespace")
	}
	if uint64(len(namespace)) > math.MaxUint32 {
		return nil, errors.New("sshsig: namespace too long")
	}
	h := sha512.Sum512(message)
	data := signedData(namespace, "", "sha512", h[:])

	pub := s.PublicKey()
	var sig *ssh.Signature
	var err error
	if isRSA(pub) {
		as, ok := s.(ssh.AlgorithmSigner)
		if !ok {
			return nil, errors.New("sshsig: an RSA signer must implement ssh.AlgorithmSigner")
		}
		algo := ssh.KeyAlgoRSASHA512
		if ms, ok := s.(ssh.MultiAlgorithmSigner); ok {
			algos := ms.Algorithms()
			if len(algos) == 0 {
				return nil, errors.New("sshsig: the signer offers no algorithms")
			}
			algo = algos[0]
		}
		if algo != ssh.KeyAlgoRSASHA256 && algo != ssh.KeyAlgoRSASHA512 {
			return nil, fmt.Errorf("sshsig: RSA signatures must be rsa-sha2-256 or rsa-sha2-512, not %q", algo)
		}
		sig, err = as.SignWithAlgorithm(rand, data, algo)
	} else {
		sig, err = s.Sign(rand, data)
	}
	if err != nil {
		return nil, err
	}

	var b []byte
	b = append(b, magicPreamble...)
	b = binary.BigEndian.AppendUint32(b, sigVersion)
	b = appendString(b, pub.Marshal())
	b = appendString(b, []byte(namespace))
	b = appendString(b, nil)
	b = appendString(b, []byte("sha512"))
	b = appendString(b, ssh.Marshal(sig))
	return b, nil
}

// Verify verifies a detached SSH Signature for the provided message.
//
// The namespace is a domain-specific identifier for the context in which the
// signature will be used. It must match between the [Sign] and Verify calls. A
// fully-qualified suffix is recommended, e.g. "receiptV2@example.com".
//
// The provided signature is usually decoded from a PEM block of type "SSH
// SIGNATURE" using [encoding/pem].
//
// The key inside the signature must equal pub. Both "sha256" and "sha512"
// message hashes are accepted, and legacy "ssh-rsa" (SHA-1) signatures are
// rejected, as PROTOCOL.sshsig requires.
func Verify(pub ssh.PublicKey, message, signature []byte, namespace string) error {
	if namespace == "" {
		return errors.New("sshsig: empty namespace")
	}
	r := reader(signature)
	magic, ok := r.take(len(magicPreamble))
	if !ok || string(magic) != magicPreamble {
		return errors.New("sshsig: not an SSH signature")
	}
	version, ok := r.uint32()
	if !ok {
		return errors.New("sshsig: truncated signature")
	}
	if version != sigVersion {
		return fmt.Errorf("sshsig: unsupported signature version %d", version)
	}
	keyBytes, ok1 := r.string()
	ns, ok2 := r.string()
	reserved, ok3 := r.string()
	hashAlg, ok4 := r.string()
	sigBytes, ok5 := r.string()
	if !ok1 || !ok2 || !ok3 || !ok4 || !ok5 {
		return errors.New("sshsig: truncated signature")
	}
	if len(r) != 0 {
		return errors.New("sshsig: trailing data after the signature")
	}

	if !bytes.Equal(keyBytes, pub.Marshal()) {
		return errors.New("sshsig: signed by a different key")
	}
	if string(ns) != namespace {
		return fmt.Errorf("sshsig: signature is for namespace %q, not %q", ns, namespace)
	}

	var h []byte
	switch string(hashAlg) {
	case "sha512":
		s := sha512.Sum512(message)
		h = s[:]
	case "sha256":
		s := sha256.Sum256(message)
		h = s[:]
	default:
		return fmt.Errorf("sshsig: unsupported hash algorithm %q", hashAlg)
	}

	sig := new(ssh.Signature)
	if err := ssh.Unmarshal(sigBytes, sig); err != nil {
		return fmt.Errorf("sshsig: malformed signature: %v", err)
	}
	switch sig.Format {
	case ssh.KeyAlgoRSA:
		return errors.New(`sshsig: legacy "ssh-rsa" (SHA-1) signatures are not accepted`)
	case ssh.KeyAlgoSKECDSA256, ssh.KeyAlgoSKED25519:
		// Security keys append their flags and counter (PROTOCOL.u2f).
	default:
		if len(sig.Rest) != 0 {
			return errors.New("sshsig: trailing data in the signature")
		}
	}

	// The reserved field is ignored, as the specification says, but it is part
	// of the signed data.
	return pub.Verify(signedData(string(ns), string(reserved), string(hashAlg), h), sig)
}

func isRSA(pub ssh.PublicKey) bool {
	t := pub.Type()
	if cert, ok := pub.(*ssh.Certificate); ok {
		t = cert.Key.Type()
	}
	return t == ssh.KeyAlgoRSA
}

// signedData is the data the key signs: PROTOCOL.sshsig §3.
func signedData(namespace, reserved, hashAlg string, hash []byte) []byte {
	var b []byte
	b = append(b, magicPreamble...)
	b = appendString(b, []byte(namespace))
	b = appendString(b, []byte(reserved))
	b = appendString(b, []byte(hashAlg))
	b = appendString(b, hash)
	return b
}

// appendString appends an RFC 4251 string: a uint32 length, then the bytes.
// Every caller's string is a key, a hash, a signature or a namespace Sign has
// bounded, so the length fits.
func appendString(b, s []byte) []byte {
	b = binary.BigEndian.AppendUint32(b, uint32(len(s))) //nolint:gosec // bounded by the callers
	return append(b, s...)
}

type reader []byte

func (r *reader) take(n int) ([]byte, bool) {
	if n < 0 || len(*r) < n {
		return nil, false
	}
	v := (*r)[:n]
	*r = (*r)[n:]
	return v, true
}

func (r *reader) uint32() (uint32, bool) {
	v, ok := r.take(4)
	if !ok {
		return 0, false
	}
	return binary.BigEndian.Uint32(v), true
}

func (r *reader) string() ([]byte, bool) {
	n, ok := r.uint32()
	if !ok || uint64(n) > uint64(len(*r)) {
		return nil, false
	}
	return r.take(int(n))
}
